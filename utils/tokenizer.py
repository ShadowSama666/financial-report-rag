_INITED = False
_punct_re = re.compile(r"[\s　!-/:-@\[-`{-~。，、；：？！…—－（）《》【】“”‘’·]+")


def init_jieba() -> None:
    """把自定义词典注册进 jieba（幂等，可重复调用）。"""
    global _INITED
    if _INITED:
        return
    jieba.setLogLevel(logging.WARNING)      # 屏蔽 jieba 的 DEBUG/INFO 刷屏
    for word in FINANCE_WORDS:
        jieba.add_word(word, freq=100000)
    _INITED = True


def tokenize(text: str, drop_stopwords: bool = True) -> list[str]:
    """切词 -> 过滤空白/标点/停用词 -> 返回词列表。

    数字（年份、金额）保留：BM25 的差异化价值就在于精确命中「2025」「毛利率」这类词。
    """
    init_jieba()
    if not text:
        return []
    tokens = jieba.lcut(text)
    out: list[str] = []
    for tok in tokens:
        tok = tok.strip()
        if not tok:
            continue
        if _punct_re.fullmatch(tok):
            continue
        if drop_stopwords and tok in STOPWORDS:
            continue
        out.append(tok.lower() if tok.isascii() else tok)
    return out
